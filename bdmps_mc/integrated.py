"""Spectrum integrated over all k (case 1 of the paper, Sec. V C).

    I = pi/(2 alpha_s C_R) omega dI/domega = Re E[ ln Phi ],   Phi = prod_j (1 + y_j zeta_j^-)   (Moebius recursion)

with y_j = g_ref m2(sigma_j)/eps_j, eps_j ~ Exp(1), and zeta -> zeta + Delta sigma between centers, zeta -> zeta/(1 + y zeta) at a center.
Estimator (Mecke's formula, the width of the marked center integrated exactly with V):

    E = int_0^{X(1)} dX* E[ V(g(sigma*) zeta(sigma*^-)) ],   sigma* = X^{-1}(X*),

where zeta(sigma*^-) is generated by the centers in (0, sigma*). X* is stratified.
Optional control variate: the same estimator without earlier centers (first order in opacity), whose mean is computed by quadrature.
"""
import numpy as np
from scipy.integrate import quad
from .vfunc import V


def _moebius(prof, gref, Xmax, rng):
    """Poisson(Xmax) centers uniform in opacity on [0, Xmax] (one Xmax per sample).
    Returns zeta just after the last center, the position of that center, and sum_j ln(1 + y_j zeta_j)."""
    M = Xmax.size
    zeta, last, lg = np.zeros(M, complex), np.zeros(M), np.zeros(M, complex)
    N = rng.poisson(Xmax)
    for k in np.unique(N):
        if k == 0:
            continue
        idx = np.where(N == k)[0]
        sj = prof.sigma(np.sort(rng.random((idx.size, k)), axis=1) * Xmax[idx, None])
        y = gref * prof.m2(sj) / rng.exponential(size=sj.shape)
        z, prev, acc = np.zeros(idx.size, complex), np.zeros(idx.size), np.zeros(idx.size, complex)
        for j in range(k):
            z = z + (sj[:, j] - prev)
            prev = sj[:, j]
            fac = 1 + y[:, j] * z
            acc += np.log(fac)
            z = z / fac
        zeta[idx], last[idx], lg[idx] = z, prev, acc
    return zeta, last, lg


def first_order(prof, gref):
    """First order in opacity, int dsigma chi(sigma) V(g(sigma) sigma), by quadrature (complex)."""
    def f(s, im):
        v = complex(prof.chi(s) * V(gref * prof.m2(s) * s))
        return v.imag if im else v.real
    kw = dict(points=list(prof.breaks) or None, limit=400, epsabs=1e-13, epsrel=1e-11)
    return quad(f, 0, 1, args=(0,), **kw)[0] + 1j * quad(f, 0, 1, args=(1,), **kw)[0]


def spectrum_integrated(prof, gref, nsamp=200000, seed=0, control=True):
    """Returns (I, error of I) with I = Re E (dimensionless integrated spectrum).
    control=True uses the first order in opacity as control variate (its mean by quadrature)."""
    rng = np.random.default_rng(seed)
    Xs = prof.Xtot * (np.arange(nsamp) + rng.random(nsamp)) / nsamp
    sig = prof.sigma(Xs)
    zeta, last, _ = _moebius(prof, gref, Xs, rng)
    g = gref * prof.m2(sig)
    A = V(g * (zeta + sig - last))
    if not control:
        return prof.Xtot * A.mean().real, prof.Xtot * A.real.std() / np.sqrt(nsamp)
    B = V(g * sig)
    cov = np.cov(A.real, B.real)
    c = cov[0, 1] / cov[1, 1]
    D = A - c * B
    return (prof.Xtot * D.mean() + c * first_order(prof, gref)).real, prof.Xtot * D.real.std() / np.sqrt(nsamp)
